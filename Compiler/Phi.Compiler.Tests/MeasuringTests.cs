        readonly string root = Path.Combine(Path.GetTempPath(), "phi-measure-" + Guid.NewGuid().ToString("N"));

        public MeasuringTests() => Directory.CreateDirectory(root);
        public void Dispose() => Directory.Delete(root, recursive: true);

        static readonly BenchOptions Usual = new(Save: false, TolerancePercent: 2);

        [Fact]
        public void BenchLinesAreReadFromTheOutputAndLeftOutOfIt()
        {
            string output = "start\nbench sha256 4 KB 1200\nmiddle\r\nbench heap 35\n";
            Assert.Equal(new[] { ("sha256 4 KB", 1200UL), ("heap", 35UL) }, BenchCheck.Parse(output));
            Assert.True(BenchCheck.IsBenchLine("bench heap 35"));
            Assert.False(BenchCheck.IsBenchLine("bench heap"));
            Assert.False(BenchCheck.IsBenchLine("a bench heap 35"));
        }

        [Fact]
        public void TheFirstRunSavesTheCountsAndLaterRunsCompareWithThem()
        {
            string baseline = Path.Combine(root, "bench_x.bench");
            var report = new List<string>();
            Assert.Null(BenchCheck.Check(baseline, "bench sha 1000\nbench aes 500\n", Usual, report));
            Assert.Equal(new Dictionary<string, ulong> { ["sha"] = 1000, ["aes"] = 500 }, BenchCheck.ReadBaseline(baseline));

            // within 2%: passes; faster: passes and says so
            report.Clear();
            Assert.Null(BenchCheck.Check(baseline, "bench sha 1015\nbench aes 400\n", Usual, report));
            Assert.Contains(report, l => l.StartsWith("aes") && l.EndsWith("faster"));

            // more than 2% over: fails, and names the count
            string? failure = BenchCheck.Check(baseline, "bench sha 1100\nbench aes 500\n", Usual, new List<string>());
            Assert.NotNull(failure);
            Assert.Contains("sha: +10.0%", failure);

            // a count that's no longer written fails too, until --save-bench forgets it
            Assert.Contains("not measured any more: aes", BenchCheck.Check(baseline, "bench sha 1000\n", Usual, new List<string>()));
            Assert.Null(BenchCheck.Check(baseline, "bench sha 1100\n", Usual with { Save = true }, new List<string>()));
            Assert.Equal(new Dictionary<string, ulong> { ["sha"] = 1100 }, BenchCheck.ReadBaseline(baseline));
        }

        [Fact]
        public void ABenchmarkWithoutCountsOrWithTwoOfTheSameNameFails()
        {
            string baseline = Path.Combine(root, "bench_y.bench");
            Assert.Contains("has to write bench lines", BenchCheck.Check(baseline, "done\n", Usual, new List<string>()));
            Assert.Contains("'sha'", BenchCheck.Check(baseline, "bench sha 1\nbench sha 2\n", Usual, new List<string>()));
            Assert.False(File.Exists(baseline));
        }

        [Fact]
        public void RegistersGiveTheAddressPrivilegeAndHaltedState()
        {
            const string kernel = "CPU#0\r\nEAX=00000000 EBX=00000040\r\nEIP=00010248 EFL=00000246 [---Z-P-] CPL=0 II=0 A20=1 SMM=0 HLT=1\r\n" +
                                  "ES =0010 00000000 ffffffff 00cf9300\r\nCS =0008 00000000 ffffffff 00cf9a00\r\n(qemu) ";
            Assert.Equal(new Profiler.Sample(0x10248, 0, true), Profiler.ParseRegisters(kernel));

            // real mode: the address is the segment's base plus eip
            const string real = "EIP=00000123 EFL=00000202 [-------] CPL=0 II=0 A20=1 SMM=0 HLT=0\r\nCS =07e0 00007e00 0000ffff 00009b00\r\n";
            Assert.Equal(new Profiler.Sample(0x7F23, 0, false), Profiler.ParseRegisters(real));
            Assert.Null(Profiler.ParseRegisters("(qemu) "));
        }

        [Fact]
        public void AnAddressMapsToItsLineMethodOrLibraryRoutine()
        {
            // a listing in NASM's layout: line number, offset, bytes, then the source from column 40
            string[] listing =
            {
                Row(1, null, "", "; 32-bit kernel generated by phi from os.phi"),
                Row(2, null, "", "org 0x10000"),
                Row(3, null, "", "phi_start:"),
                Row(4, null, "", "    ; ---- class Os (os.phi)"),
                Row(5, null, "", "    ; 3: call Work;"),
                Row(6, 0x0, "E810000000", "    call M_Os_Work"),
                Row(7, null, "", "    ; method Os.Work (os.phi)"),
                Row(8, null, "", "M_Os_Work:"),
                Row(9, 0x5, "55", "    push ebp"),
                Row(10, null, "", "    ; 7: total++ i;"),
                Row(11, 0x6, "FF05[00100100]", "    inc dword [VALUE_total]"),
                Row(12, null, "", "phi_while_3:"),      // a jump target: still line 7
                Row(13, 0xC, "EBF8", "    jmp phi_while_3"),
                Row(14, null, "", "; ---- library: console.asm"),
                Row(15, null, "", "phi_print:"),
                Row(16, 0xE, "AC", "    lodsb"),
                Row(17, null, "", ".done:"),
                Row(18, 0xF, "C3", "    ret"),
                Row(19, null, "", "; ---- data"),
                Row(20, 0x1000, "00000000", "VALUE_total: dd 0"),
            };
            AddressMap map = AddressMap.Parse(listing);

            Assert.Equal(new CodePlace("Os (class body)", "os.phi", 3, "call Work;"), map.Find(0x10000));
            Assert.Equal(new CodePlace("Os.Work", "os.phi", 0, ""), map.Find(0x10005));
            Assert.Equal(new CodePlace("Os.Work", "os.phi", 7, "total++ i;"), map.Find(0x10008));
            Assert.Equal(new CodePlace("Os.Work", "os.phi", 7, "total++ i;"), map.Find(0x1000C));
            Assert.Equal(new CodePlace("phi_print", "console.asm", 0, ""), map.Find(0x1000F));
            Assert.Null(map.Find(0x11000));     // the variables aren't code
            Assert.Null(map.Find(0x0FFFF));
        }

        [Fact]
        public void ARealKernelsListingMapsEachLineToItsCode()
        {
            File.WriteAllText(Path.Combine(root, "os.phi"),
                "phi.Os:Kernel\n{\n\tint total: 0;\n\tcall Work;\n\tlog total;\n\n\t[Work]\n" +
                "\t\twhile int i: 0; i < 10; i++;\n\t\t\ttotal++ i;\n\t\t;;\n\t[end]\n}\n");
            BuildResult result = Builder.Build(Path.Combine(root, "os.phi"), Path.Combine(root, "build"), listing: true);
            Assert.True(result.Success, string.Join("\n", result.Errors));

            string[] lines = File.ReadAllLines(Path.Combine(root, "build", "kernel.lst"));
            AddressMap map = AddressMap.Parse(lines);

            // the first instruction after each line's comment is that line's code
            Assert.Equal(("Os.Work", 9), Place(map, FirstCodeAfter(lines, "; 9: total++ i;")));
            Assert.Equal(("Os (class body)", 4), Place(map, FirstCodeAfter(lines, "; 4: call Work;")));
            Assert.Equal(("phi_print", 0), Place(map, FirstCodeAfter(lines, "phi_print:")));
            Assert.EndsWith("/os.phi", map.Find(FirstCodeAfter(lines, "; 9: total++ i;"))!.File);
        }

        /// <summary>A kernel's listing with a call, a method written out in its caller, and a library routine.</summary>
        static readonly string[] CallingListing =
        {
            Row(1, null, "", "; 32-bit kernel generated by phi from os.phi"),
            Row(1, null, "", "org 0x10000"),
            Row(2, null, "", "    ; ---- class Os (os.phi)"),
            Row(3, null, "", "    ; 3: call Work;"),
            Row(4, 0x0, "E810000000", "    call M_Os_Work"),
            Row(5, null, "", "    ; 4: call Small;"),
            Row(6, null, "", "    ; Os.Small, written out here (small.phi)"),
            Row(7, null, "", "    ; 2: call phi_print;"),
            Row(8, 0x5, "E8[04000000]", "    call phi_print"),
            Row(9, null, "", "    ; Os.Small, written out up to here"),
            Row(10, 0xA, "FFD0", "    call eax"),
            Row(11, null, "", "    ; method Os.Work (os.phi)"),
            Row(12, null, "", "M_Os_Work:"),
            Row(13, null, "", "    ; 7: while true"),
            Row(14, 0xC, "EBFE", "    jmp $"),
            Row(15, null, "", "; ---- library: console.asm"),
            Row(16, null, "", "phi_print:"),
            Row(17, 0xE, "C3", "    ret"),
        };

        [Fact]
        public void TheMapKnowsWhereEachCallReturnsToAndWhichCodeWasWrittenOutInPlace()
        {
            AddressMap map = AddressMap.Parse(CallingListing);
            Assert.True(map.IsReturn(0x10005));         // after the 5-byte call at 0x10000
            Assert.True(map.IsReturn(0x1000A));         // [] around an address NASM fills in doesn't count
            Assert.True(map.IsReturn(0x1000C));         // call eax: two bytes
            Assert.False(map.IsReturn(0x10000));
            Assert.False(map.IsReturn(0x1_0000_0005));  // a 64-bit value isn't one

            // the written-out method's lines are its own, in its own file; after it, the caller's again
            Assert.Equal(new CodePlace("Os.Small (written out in Os (class body))", "small.phi", 2, "call phi_print;"), map.Find(0x10005));
            Assert.Equal(new CodePlace("Os (class body)", "os.phi", 4, "call Small;"), map.Find(0x1000A));
        }

        [Fact]
        public void AStoppedThreadIsShownWithTheCallsOnItsStack()
        {
            var maps = new List<NamedMap> { new("", AddressMap.Parse(CallingListing)) };
            var threads = new List<StoppedThread>
            {
                // in Work, called from the class body (0x10005), with other values around it
                new("thread 1", 0x1000C, new ulong[] { 7, 0x10005, 0x10003, 0x1_0000_0005 }),
                // in the system's code, called from the written-out method (0x1000A)
                new("thread 2", 0x7FFE0000, new ulong[] { 0x1000A }, "in system call 240 (futex)"),
                new("thread 3", 0x7FFE0000, new ulong[] { 0x1000A }, "in system call 240 (futex)"),
                new("thread 4", 0x7FFE0000, new ulong[] { 1, 2, 3 }),           // the system's own
                new("cpu 1", 0xFD0A9, Array.Empty<ulong>(), "waiting for an interrupt (hlt)", Always: true),
            };
            Assert.Equal(
                "where it was when it was stopped:\n" +
                "  thread 1: Os.Work, os.phi:7: while true\n" +
                "      called from Os (class body), os.phi:3: call Work;\n" +
                "  thread 2, thread 3: in the system's code (0x7FFE0000), in system call 240 (futex)\n" +
                "      called from Os.Small (written out in Os (class body)), small.phi:2: call phi_print;\n" +
                "  cpu 1: outside the program's code (0xFD0A9), waiting for an interrupt (hlt)\n" +
                "  (1 other thread, with no PHI code on its stack: the system's own)",
                Where.Report(threads, maps));
            Assert.Equal("", Where.Report(Array.Empty<StoppedThread>(), maps));
        }

        [Fact]
        public void ALinuxProgramsThreadsAreReadFromWhatProcSays()
        {
            // what the script prints: each thread's /proc syscall line, then its stack's bytes
            string printed =
                "T 501 162 0xbffff000 0x0 0x0 0x0 0x0 0x0 0xbfffe000 0x08049010\n" +
                " 05 00 01 00 07 00 00 00\n" +
                "T 503 -1 0xb7000000 0x08049020\n" +
                " 0a 00 01 00\n" +
                "T 502 running\n";
            List<StoppedThread> threads = Where.FromLinux("pid", is64: false, (_, file) => file == "pid" ? printed : "");
            Assert.Equal(3, threads.Count);
            Assert.Equal(("thread 1", 0x08049010UL, "in system call 162 (nanosleep)"), (threads[0].Name, threads[0].Ip, threads[0].Note));
            Assert.Equal(new ulong[] { 0x10005, 7 }, threads[0].Stack);
            Assert.Equal(("thread 2", "running"), (threads[1].Name, threads[1].Note));
            Assert.Equal(("thread 3", 0x08049020UL, (string?)null), (threads[2].Name, threads[2].Ip, threads[2].Note));
            Assert.Equal(new ulong[] { 0x1000A }, threads[2].Stack);
        }

